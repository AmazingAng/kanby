function hash(value) {
  return createHash('sha256').update(value).digest('hex');
}

// Run a focused subset with MUTATION_FILTER='mini board backend' node tools/mutants.mjs.
const filter = process.env.MUTATION_FILTER;
const selected = filter
  ? mutations.filter((mutation) => mutation.name.includes(filter))
  : mutations;
if (selected.length === 0) throw new Error(`No mutations match: ${filter}`);

for (const mutation of selected) {
  const original = readFileSync(mutation.file, 'utf8');
  const occurrences = original.split(mutation.from).length - 1;
  if (occurrences !== 1) {
    throw new Error(
      `${mutation.name}: expected exactly one mutation target, found ${occurrences}`,
    );
  }
  const originalHash = hash(original);
  writeFileSync(mutation.file, original.replace(mutation.from, mutation.to));
  let result;
  try {
    result = spawnSync(
      'npx',
      [
        'vitest',
        'run',
        mutation.test,
        ...(mutation.testName ? ['-t', mutation.testName] : []),
      ],
      {
        encoding: 'utf8',
        stdio: 'pipe',
      },
    );
  } finally {
    writeFileSync(mutation.file, original);
  }
  if (hash(readFileSync(mutation.file, 'utf8')) !== originalHash) {
    throw new Error(`${mutation.name}: source restoration failed`);
  }
  if (result.error || result.signal || result.status === null) {
    throw new Error(
      `${mutation.name}: mutation test did not complete normally`,
    );
  }
  if (result.status === 0) {
    process.stderr.write(result.stdout);
    process.stderr.write(result.stderr);
    throw new Error(`${mutation.name}: mutant survived`);
  }
  process.stdout.write(`KILLED: ${mutation.name}\n`);
}

process.stdout.write(
  `Mutation gate passed: ${selected.length}/${selected.length} killed.\n`,
);
